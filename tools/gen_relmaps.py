# 相関図SVG(章ごと・ライト/ダーク)を 1本の TS モジュールへ埋め込む。
# 画像(PNG)ではなく SVG文字列を同梱し、react-native-svg の SvgXml で描く
# 無劣化で拡大できる。変更の配信にはコードOTAが必要。
import json, pathlib

base = pathlib.Path('assets/relation-maps')
out = {}
for ch in '123456':
    light = (base / f'chapter{ch}_relation_map.svg').read_text(encoding='utf-8')
    dark = (base / f'chapter{ch}_relation_map-dark.svg').read_text(encoding='utf-8')
    out[ch] = {'light': light, 'dark': dark}

ts = (
    '// 自動生成（tools/gen_relmaps.py）。assets/relation-maps/*.svg を同梱用に文字列化したもの。\n'
    '// 手で編集しない。元SVGを直したら python tools/gen_relmaps.py で再生成する。\n'
    'export const RELATION_MAPS: Record<string, { light: string; dark: string }> = '
    + json.dumps(out, ensure_ascii=False)
    + ';\n'
)
dst = pathlib.Path('src/data/relationMaps.generated.ts')
dst.write_text(ts, encoding='utf-8')
total = sum(len(v['light']) + len(v['dark']) for v in out.values())
print(f'wrote {dst} ({total} bytes of svg, {len(out)} chapters)')

# The optional PNG registry must not carry another stale copy of the SVG text.
registry = '''// Generated by tools/gen_relmaps.py; do not edit.
import type { ImageSourcePropType } from 'react-native';
import { RELATION_MAPS as SVG_MAPS } from './relationMaps.generated';
import content from '../../docs/relation-maps/structure.json';
export type RelationMap = { chapter: number; title: string; description: string; themes: readonly string[]; width: number; height: number; light: ImageSourcePropType; dark: ImageSourcePropType; lightSvg: string; darkSvg: string };
const images = [
'''
for ch in '123456':
    registry += f"  {{ light: require('../../assets/relation-maps/chapter{ch}_relation_map.png'), dark: require('../../assets/relation-maps/chapter{ch}_relation_map-dark.png') }},\n"
registry += '''];
export const RELATION_MAPS: readonly RelationMap[] = content.chapters.map((m, i) => ({
  chapter: m.chapter, title: m.title,
  description: '6つのテーマから、用語の役割とつながりをたどります。',
  themes: m.branches.map((branch) => branch.title),
  width: content.size[0], height: content.size[1], ...images[i],
  lightSvg: SVG_MAPS[String(m.chapter)].light, darkSvg: SVG_MAPS[String(m.chapter)].dark,
}));
'''
pathlib.Path('src/data/relationMaps.ts').write_text(registry, encoding='utf8')
