"""Embed generated relationship SVGs. Author the canonical Markdown, not SVG/TS."""
import json
from pathlib import Path
R = Path(__file__).resolve().parents[1]
data = json.loads((R / 'docs/relation-maps/structure.json').read_text(encoding='utf8'))
out = {}
for chapter in data['chapters']:
    for diagram in chapter['diagrams']:
        out[f'{chapter["chapter"]}/{diagram["id"]}'] = {
            theme: (R / 'assets/relation-maps' / (diagram['asset'] + suffix + '.svg')).read_text(encoding='utf8')
            for theme, suffix in [('light', ''), ('dark', '-dark')]
        }
ts = '// Generated by tools/build_relation_maps.py from 教材解説/相関図.md; do not edit.\n'
ts += 'export const RELATION_MAPS: Record<string, { light: string; dark: string }> = ' + json.dumps(out, ensure_ascii=False) + ';\n'
(R / 'src/data/relationMaps.generated.ts').write_text(ts, encoding='utf8', newline='\n')
registry = '''// Generated by tools/gen_relmaps.py; first diagram preview for each chapter.
import type { ImageSourcePropType } from 'react-native';
import { RELATION_MAPS as SVG_MAPS } from './relationMaps.generated';
import content from '../../docs/relation-maps/structure.json';
export type RelationMap = { chapter: number; title: string; description: string; themes: readonly string[]; width: number; height: number; light: ImageSourcePropType; dark: ImageSourcePropType; lightSvg: string; darkSvg: string };
const images = [
'''
for ch in data['chapters']:
    asset = ch['diagrams'][0]['asset']
    registry += f"  {{ light: require('../../assets/relation-maps/{asset}.png'), dark: require('../../assets/relation-maps/{asset}-dark.png') }},\n"
registry += '''];
export const RELATION_MAPS: readonly RelationMap[] = content.chapters.map((m, i) => ({
  chapter: m.chapter, title: m.title, description: m.diagrams[0].question,
  themes: m.diagrams.map(d => d.title),
  width: m.diagrams[0].width, height: m.diagrams[0].height, ...images[i],
  lightSvg: SVG_MAPS[m.chapter + '/' + m.diagrams[0].id].light,
  darkSvg: SVG_MAPS[m.chapter + '/' + m.diagrams[0].id].dark,
}));
'''
(R / 'src/data/relationMaps.ts').write_text(registry, encoding='utf8', newline='\n')
print(f'Embedded {len(out)} relationship diagrams')
